CREATE TABLE IF NOT EXISTS tutor_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    qualification VARCHAR(255) NOT NULL,
    experience_years INTEGER NOT NULL CHECK (experience_years >= 0),
    bio TEXT NOT NULL,
    subject VARCHAR(255) NOT NULL,
    location VARCHAR(255) NOT NULL,
    hourly_rate NUMERIC(10, 2) NOT NULL CHECK (hourly_rate >= 0),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_tutor_profiles_subject ON tutor_profiles (subject);
CREATE INDEX IF NOT EXISTS idx_tutor_profiles_location ON tutor_profiles (location);
CREATE INDEX IF NOT EXISTS idx_tutor_profiles_rate ON tutor_profiles (hourly_rate);
