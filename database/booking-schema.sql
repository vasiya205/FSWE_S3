CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_user_id BIGINT NOT NULL,
    tutor_user_id BIGINT NOT NULL,
    subject VARCHAR(255) NOT NULL,
    start_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    end_date_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    notes TEXT NOT NULL,
    hourly_rate NUMERIC(10, 2) NOT NULL CHECK (hourly_rate >= 0),
    status VARCHAR(255) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'COMPLETED', 'CANCELLED')),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_date_time > start_date_time)
);

CREATE INDEX IF NOT EXISTS idx_bookings_student ON bookings (student_user_id);
CREATE INDEX IF NOT EXISTS idx_bookings_tutor ON bookings (tutor_user_id);
CREATE INDEX IF NOT EXISTS idx_bookings_time ON bookings (start_date_time, end_date_time);

CREATE TABLE IF NOT EXISTS reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings (id) ON DELETE RESTRICT,
    student_user_id BIGINT NOT NULL,
    tutor_user_id BIGINT NOT NULL,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment TEXT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_reviews_tutor ON reviews (tutor_user_id);
CREATE INDEX IF NOT EXISTS idx_reviews_booking ON reviews (booking_id);
